export function resolveLocale(value) {
  const tag = String(value || '').toLowerCase().replaceAll('_', '-');
  if (tag.startsWith('zh')) return /(?:cn|sg|hans)/.test(tag) ? 'zh-CN' : 'zh-TW';
  if (tag.startsWith('pt')) return 'pt-BR';
  return Object.keys(messages).find(locale => tag === locale.toLowerCase() || tag.startsWith(`${locale.toLowerCase()}-`)) || 'en';
}
export function t(locale, key, values = {}) {
  const text = messages[resolveLocale(locale)][key] ?? messages.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
