'use strict';
const { app, BrowserWindow, utilityProcess, ipcMain } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { createPluginBackends } = require('../src/electron/plugins/backend');
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'tm-trusted-'));
app.setPath('userData', path.join(scratch, 'profile'));
const root = path.resolve(__dirname, '..');
let backend, win, server;
const check = (label, fn) => { fn(); console.log(`PASS ${label}`); };
app.whenReady().then(async () => {
  const data = [];
  backend = createPluginBackends({ fork: utilityProcess.fork, hostCall: (_id, _method, value) => ({ host: value }), onData: (_id, value) => data.push(value), onError: (_id, message) => console.error(message) });
  check('no backend before demand', () => assert.equal(backend.size(), 0));
  const entry = path.join(root, 'tests/fixtures/trusted-plugin/backend.cjs');
  await Promise.all([backend.start('fixture', entry, path.join(scratch, 'data')), backend.start('fixture', entry, path.join(scratch, 'data'))]);
  check('one shared backend', () => assert.equal(backend.size(), 1));
  const first = await backend.call('fixture', 'echo', 'first');
  const second = await backend.call('fixture', 'echo', 'second');
  check('shared process identity', () => assert.equal(first.pid, second.pid));
  check('local filesystem', () => {});
  assert.equal(await backend.call('fixture', 'file', 'synthetic only'), 'synthetic only');
  server = http.createServer((_request, response) => response.end('loopback only'));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  assert.equal(await backend.call('fixture', 'fetch', `http://127.0.0.1:${server.address().port}`), 'loopback only');
  console.log('PASS local network');
  assert.deepEqual(await backend.call('fixture', 'host', 7), { host: 7 });
  console.log('PASS formal host call');
  await assert.rejects(backend.call('fixture', 'fail'), /Intentional/);
  console.log('PASS backend error remains actionable');
  ipcMain.handle('fixture:call', (_event, method, value) => backend.call('fixture', method, value));
  const preload = path.join(scratch, 'preload.cjs');
  fs.writeFileSync(preload, "const {contextBridge,ipcRenderer}=require('electron');contextBridge.exposeInMainWorld('fixture',{call:(m,v)=>ipcRenderer.invoke('fixture:call',m,v)});");
  const html = path.join(scratch, 'index.html');
  fs.writeFileSync(html, `<html><body><main id="mount"></main><script src="${pathToFileURL(path.join(root, 'src/electron/renderer/pluginUi.js')).href}"></script></body></html>`);
  win = new BrowserWindow({ show: false, webPreferences: { preload, contextIsolation: true, nodeIntegration: false, sandbox: true } });
  await win.loadFile(html);
  const result = await win.webContents.executeJavaScript(`(async()=>{
    const host=TokenMonitorPluginUi.createHost({document,window,bridge:{call:(_id,m,v)=>fixture.call(m,v)}});
    const descriptor={pluginId:'fixture',id:'test',ref:'fixture/test',revision:1,entry:${JSON.stringify(pathToFileURL(path.join(root, 'tests/fixtures/trusted-plugin/ui.mjs')).href)}};
    const container=document.getElementById('mount');
    await host.mount(container,descriptor,{surface:'home'});
    const input=container.querySelector('input');input.value='draft';
    await host.mount(container,descriptor,{surface:'page'});
    await container.querySelector('button').onclick();
    const result={sameInput:input===container.querySelector('input'),dirty:host.hasUnsavedChanges(),reply:JSON.parse(container.querySelector('output').textContent),node:typeof require};
    await host.dispose(); result.empty=container.children.length===0; return result;
  })()`);
  assert.equal(result.sameInput, true); assert.equal(result.dirty, true); assert.equal(result.reply.value, 'draft'); assert.equal(result.reply.pid, first.pid); assert.equal(result.node, 'undefined'); assert.equal(result.empty, true);
  console.log('PASS same-page UI, backend bridge, retained draft, disposal and renderer Node isolation');
  await backend.call('fixture', 'start');
  await new Promise(resolve => setTimeout(resolve, 180));
  assert.ok(data.length > 0); backend.stop('fixture');
  const count = data.length;
  await new Promise(resolve => setTimeout(resolve, 150));
  assert.equal(data.length, count); assert.equal(backend.size(), 0);
  console.log('PASS stopped backend emits no more data');
  console.log(JSON.stringify({ electron: process.versions.electron, chromium: process.versions.chrome, result }));
  app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
app.on('will-quit', () => { backend?.dispose(); server?.close(); win?.destroy(); });
